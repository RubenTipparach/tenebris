# ---------------------------------------------------------------------------

def make_rgba_canvas(w, h):
    return [[(0, 0, 0, 0)] * w for _ in range(h)]


def paint_pattern(canvas, col, row, pattern):
    """Stamp a 16x16 string-grid into the atlas at the given tile
    coordinate. Lines with the wrong width are padded / truncated to
    TILE_PX so a typo in the pattern doesn't smear the next row."""
    rows = [line for line in pattern.split("\n") if line]
    base_x = col * TILE_PX
    base_y = row * TILE_PX
    for j in range(TILE_PX):
        line = rows[j] if j < len(rows) else "." * TILE_PX
        line = (line + "." * TILE_PX)[:TILE_PX]
        for i, ch in enumerate(line):
            rgba = PAL.get(ch, PAL["."])
            if rgba[3] == 0:
                continue
            canvas[base_y + j][base_x + i] = rgba


def write_png_rgba(path, w, h, canvas):
    raw = bytearray()
    for j in range(h):
        raw.append(0)  # filter byte: none
        for i in range(w):
            r, g, b, a = canvas[j][i]
            raw.extend((r & 0xff, g & 0xff, b & 0xff, a & 0xff))

    def chunk(tag, data):
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    sig = b"\x89PNG\r\n\x1a\n"
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)
    idat = zlib.compress(bytes(raw), 9)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(sig)
        f.write(chunk(b"IHDR", ihdr))
        f.write(chunk(b"IDAT", idat))
        f.write(chunk(b"IEND", b""))


def main():
    canvas = make_rgba_canvas(ATLAS_W, ATLAS_H)
    for col, row, pattern, name in LAYOUT:
        paint_pattern(canvas, col, row, pattern)

    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.normpath(os.path.join(here, "..", "assets", "textures",
                                          "items", "atlas.png"))
    write_png_rgba(out, ATLAS_W, ATLAS_H, canvas)
    print(f"wrote {out} ({ATLAS_W}x{ATLAS_H} RGBA, {len(LAYOUT)} icons)")


if __name__ == "__main__":
    main()
