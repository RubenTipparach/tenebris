// The NPC rules for the multiplayer server (openspec friendship-npcs,
// design 2): bundles src/shared/npc (and the config it reads) with esbuild
// (already installed with vite) into server-js/npc-core.js, a plain ES
// module the server imports - the server has no TypeScript build, and a
// hand-written JS copy of the rules would drift. scripts/npc-core.test.ts
// rebuilds it and fails when the shipped file differs.
//
// Run: npx tsx scripts/gen-npc-core.ts
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

export const NPC_CORE_PATH = fileURLToPath(new URL('../server-js/npc-core.js', import.meta.url));
const ROOT = fileURLToPath(new URL('..', import.meta.url));
const ENTRY = 'src/shared/npc/index.ts';

const BANNER = `// GENERATED by scripts/gen-npc-core.ts from ${ENTRY} - do not edit.
// Regenerate: npx tsx scripts/gen-npc-core.ts (scripts/npc-core.test.ts fails on drift).`;

/** The bundle as text (deterministic for a given source and esbuild version). */
export async function buildNpcCore(): Promise<string> {
  const out = await build({
    absWorkingDir: ROOT,          // so the bundle's path comments are repo-relative
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'es2020',
    charset: 'utf8',
    legalComments: 'none',
    banner: { js: BANNER },
    logLevel: 'silent',
  });
  return out.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(NPC_CORE_PATH, await buildNpcCore());
  console.log(`wrote ${NPC_CORE_PATH}`);
}
