/* ------------------------------------------------------------------
 * Explicit little-endian primitive encoders / decoders. Host byte
 * order is not assumed - same rationale as the C source.
 * ------------------------------------------------------------------ */

#[inline]
fn put_u16_le(b: &mut [u8], off: usize, v: u16) {
    b[off..off + 2].copy_from_slice(&v.to_le_bytes());
}

#[inline]
fn put_u32_le(b: &mut [u8], off: usize, v: u32) {
    b[off..off + 4].copy_from_slice(&v.to_le_bytes());
}

#[inline]
fn put_u64_le(b: &mut [u8], off: usize, v: u64) {
    b[off..off + 8].copy_from_slice(&v.to_le_bytes());
}

#[inline]
fn get_u16_le(b: &[u8], off: usize) -> u16 {
    u16::from_le_bytes([b[off], b[off + 1]])
}

#[inline]
fn get_u32_le(b: &[u8], off: usize) -> u32 {
    u32::from_le_bytes([b[off], b[off + 1], b[off + 2], b[off + 3]])
}

#[inline]
fn get_u64_le(b: &[u8], off: usize) -> u64 {
    let mut a = [0u8; 8];
    a.copy_from_slice(&b[off..off + 8]);
    u64::from_le_bytes(a)
}

/* IEEE-754 floats / doubles travel as their little-endian bit
 * patterns, exactly like the C side's memcpy-through-uint trick. */

#[inline]
fn put_f32_le(b: &mut [u8], off: usize, v: f32) {
    put_u32_le(b, off, v.to_bits());
}

#[inline]
fn get_f32_le(b: &[u8], off: usize) -> f32 {
    f32::from_bits(get_u32_le(b, off))
}

#[inline]
fn put_f64_le(b: &mut [u8], off: usize, v: f64) {
    put_u64_le(b, off, v.to_bits());
}

#[inline]
fn get_f64_le(b: &[u8], off: usize) -> f64 {
    f64::from_bits(get_u64_le(b, off))
}

/* ------------------------------------------------------------------
 * Encode / decode helpers. All functions assume little-endian on the
 * wire regardless of host byte order. Encoders return the total
 * bytes written (header + payload), or 0 if the buffer was too small.
 * Decoders return None on malformed input.
 * ------------------------------------------------------------------ */

/// `proto_write_header`. Panics if `buf` is shorter than
/// MSG_HEADER_SIZE - the C version assumes the caller checked, and
/// every encoder below does.
pub fn write_header(buf: &mut [u8], kind: MsgKind, version: u16, payload_len: u32) -> usize {
    put_u16_le(buf, 0, kind as u16);
    put_u16_le(buf, 2, version);
    put_u32_le(buf, 4, payload_len);
    MSG_HEADER_SIZE
}

/// `proto_read_header`
pub fn read_header(buf: &[u8]) -> Option<MsgHdr> {
    if buf.len() < MSG_HEADER_SIZE {
        return None;
    }
    Some(MsgHdr {
        kind: get_u16_le(buf, 0),
        version: get_u16_le(buf, 2),
        length: get_u32_le(buf, 4),
    })
}

