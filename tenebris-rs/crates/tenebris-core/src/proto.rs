/// `proto_write_water_origins_diff`. Clamps `entry_count` to
/// MSG_WATER_ORIGINS_DIFF_MAX_ENTRIES; the pad bytes in the header
/// and in every entry are always written as zero (the C encoder
/// ignores the struct's `_pad` fields on encode).
pub fn write_water_origins_diff(buf: &mut [u8], m: &MsgWaterOriginsDiff) -> usize {
    let mut n = m.entry_count as usize;
    if n > MSG_WATER_ORIGINS_DIFF_MAX_ENTRIES {
        n = MSG_WATER_ORIGINS_DIFF_MAX_ENTRIES;
    }
    let body = MSG_WATER_ORIGINS_DIFF_HEADER_SIZE + n * MSG_WATER_ORIGINS_DIFF_ENTRY_SIZE;
    let total = MSG_HEADER_SIZE + body;
    if buf.len() < total {
        return 0;
    }
    /* The C source casts the payload length through uint16_t here;
     * the max body (12 + 20*128 = 2572) fits, so the cast is
     * value-preserving and the wire bytes are identical. */
    write_header(
        buf,
        MsgKind::WaterOriginsDiff,
        MSG_WATER_ORIGINS_DIFF_VERSION,
        body as u16 as u32,
    );
    let p = &mut buf[MSG_HEADER_SIZE..];
    put_u32_le(p, 0, m.body_id);
    put_u32_le(p, 4, m.tile_idx);
    /* uint16 count + uint16 pad. */
    p[8] = (n & 0xFF) as u8;
    p[9] = ((n >> 8) & 0xFF) as u8;
    p[10] = 0;
    p[11] = 0;
    let mut off = MSG_WATER_ORIGINS_DIFF_HEADER_SIZE;
    for e in &m.entries[..n] {
        p[off] = e.depth;
        p[off + 1] = e.origin_count;
        p[off + 2] = 0;
        p[off + 3] = 0;
        for j in 0..3 {
            /* All 3 origin slots travel even when origin_count < 3. */
            put_u32_le(p, off + 4 + j * 4, e.origin_tile[j]);
        }
        p[off + 16] = e.origin_depth[0];
        p[off + 17] = e.origin_depth[1];
        p[off + 18] = e.origin_depth[2];
        p[off + 19] = 0;
        off += MSG_WATER_ORIGINS_DIFF_ENTRY_SIZE;
    }
    total
}

/// `proto_read_water_origins_diff`
pub fn read_water_origins_diff(payload: &[u8]) -> Option<MsgWaterOriginsDiff> {
    if payload.len() < MSG_WATER_ORIGINS_DIFF_HEADER_SIZE {
        return None;
    }
    let mut out = MsgWaterOriginsDiff::default();
    out.body_id = get_u32_le(payload, 0);
    out.tile_idx = get_u32_le(payload, 4);
    out.entry_count = (payload[8] as u16) | ((payload[9] as u16) << 8);
    out._pad = 0;
    let n = out.entry_count as usize;
    if n > MSG_WATER_ORIGINS_DIFF_MAX_ENTRIES {
        return None;
    }
    let need = MSG_WATER_ORIGINS_DIFF_HEADER_SIZE + n * MSG_WATER_ORIGINS_DIFF_ENTRY_SIZE;
    if payload.len() < need {
        return None;
    }
    let mut off = MSG_WATER_ORIGINS_DIFF_HEADER_SIZE;
    for e in &mut out.entries[..n] {
        e.depth = payload[off];
        e.origin_count = payload[off + 1];
        e._pad = [0, 0];
        for j in 0..3 {
            e.origin_tile[j] = get_u32_le(payload, off + 4 + j * 4);
        }
        e.origin_depth[0] = payload[off + 16];
        e.origin_depth[1] = payload[off + 17];
        e.origin_depth[2] = payload[off + 18];
        e._pad2 = 0;
        off += MSG_WATER_ORIGINS_DIFF_ENTRY_SIZE;
    }
    Some(out)
}

