//! Port of `tenebris-c/src/core/proto.{c,h}`.
//!
//! Tenebris wire protocol. Both the dedicated server and the WASM
//! client speak this. Every message on the wire is:
//!
//! ```text
//!     [ MsgHdr : 8 bytes ]  [ payload : header.length bytes ]
//! ```
//!
//! Header fields and all payloads are little-endian. Payloads are
//! encoded / decoded through the `write_*` / `read_*` helpers below -
//! never by transmuting a struct, because the in-memory layout doesn't
//! match the wire layout once any field crosses an alignment boundary.
//!
//! Versioning: each kind carries its own version. Bump it in lockstep
//! with the wire change. Old peers reject unknown versions with a
//! CLOSE rather than silently misparse.
//!
//! Byte compatibility with the C build is the entire point of this
//! module: a C client must be able to talk to the Rust server. Every
//! message id, field order, field width, endianness and quirk of the
//! C encoder (e.g. torch entries packing `op | reserved8 << 8 |
//! reserved16 << 16` into one u32, water-origin entries always
//! emitting all 3 origin slots) is replicated exactly. Pinned-byte
//! tests at the bottom were generated by running the actual C
//! encoders (gcc, tenebris-c/src/core/proto.c).
//!
//! Renames from C (rule 4 in PORTING.md - drop the redundant module
//! prefix):
//!   - `proto_write_xxx(buf, cap, m)` -> `proto::write_xxx(buf, m)`
//!     (the cap is `buf.len()`); still returns total bytes written or
//!     0 if the buffer was too small, exactly like C.
//!   - `proto_read_xxx(payload, len, out)` (0 = ok, -1 = malformed)
//!     -> `proto::read_xxx(payload) -> Option<MsgXxx>` (`None` =
//!     C's -1). The bounds checks are the same ones, in the same
//!     order.
//!   - `msg_hello_t` -> `MsgHello`, `msg_hdr_t` -> `MsgHdr`, etc.
//!   - C enums become a `#[repr(u16)] MsgKind` (exact numeric values)
//!     plus plain consts for the small reason/op enums, typed to match
//!     the struct field that carries them on the wire.

pub const MSG_HEADER_SIZE: usize = 8;

/// Sentinel for the `body_id` field of PLAYER_STATE / WELCOME /
/// SNAPSHOT entries. Indicates "the player is in deep space, not
/// gravitationally bound to any registered body". The position
/// fields remain absolute world coords; only the body anchor is
/// undefined. Valid body ids are 0..BODY_COUNT-1, so 0xFFFFFFFF can
/// never collide with a real body.
pub const BODY_ID_IN_SPACE: u32 = 0xFFFF_FFFF;

/// `msg_kind_t`. Exact numeric values - these are on the wire.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u16)]
pub enum MsgKind {
    None = 0,
    /// C->S handshake init
    Hello = 1,
    /// S->C handshake reply
    Welcome = 2,
    /// C->S input bitfield + look
    Input = 3,
    /// C->S place / break / interact / teleport
    PlayerCmd = 4,
    /// C->S relayed pose (M4 position-relay path)
    PlayerState = 5,
    /// S->C entity state
    Snapshot = 10,
    /// S->C block edits
    ChunkDiff = 11,
    /// S->C "your reported pose is impossible"
    Desync = 12,
    /// S->C name announcement: (player_id, name)
    PlayerInfo = 13,
    /// S->C terminal error + user-facing reason
    Kick = 14,
    Chat = 20,
    /// C->S: please re-send PLAYER_INFO for this id
    PlayerInfoRequest = 21,
    /// S->C: cannot fulfill PLAYER_INFO_REQUEST
    PlayerInfoNack = 22,
    /// both ways: client uploads hotbar; server replays on rejoin
    InventoryState = 23,
    /// both ways: torch place / remove (single entry C->S, broadcast
    /// S->C, bulk on join)
    TorchDiff = 24,
    /// S->C: per-voxel water flow state bytes for one tile column.
    WaterStateDiff = 25,
    /// S->C: "please fetch a fresh /saves/body and ACK when applied."
    SyncTick = 26,
    /// C->S: echoes the SYNC_TICK seq_id once applied.
    SyncAck = 27,
    /// S->C: flow-origin list for every active water cell in one tile.
    WaterOriginsDiff = 28,

    /* ---- MP-parity extensions (Rust port only, appended past the C
     * set). Both the C and Rust clients ignore unknown kinds, so these
     * are safe on the shared wire: an old C web client in the same room
     * simply skips them. Append-only, never renumber. */
    /// S->C: authoritative simulation clock (drives day/night + orbits
    /// + crop growth so every peer sees the same sun).
    SimTime = 29,
    /// C->S upload on change; S->C replay on rejoin. Bag slots + hunger.
    BagState = 30,
    /// Both ways: block-entity (machine state) records. Single entry
    /// C->S after a local machine op, broadcast S->C, bulk on join.
    BentityDiff = 31,
    /// Both ways: crop plant / remove. Single entry C->S, broadcast
    /// S->C, bulk on join.
    CropDiff = 32,
    /// S->C: replace-all herd state for one body (+ kill credit).
    AnimalState = 33,
    /// C->S: melee swing damage on one animal.
    AnimalHit = 34,
}

impl MsgKind {
    pub fn from_u16(v: u16) -> Option<MsgKind> {
        Some(match v {
            0 => MsgKind::None,
            1 => MsgKind::Hello,
            2 => MsgKind::Welcome,
            3 => MsgKind::Input,
            4 => MsgKind::PlayerCmd,
            5 => MsgKind::PlayerState,
            10 => MsgKind::Snapshot,
            11 => MsgKind::ChunkDiff,
            12 => MsgKind::Desync,
            13 => MsgKind::PlayerInfo,
            14 => MsgKind::Kick,
            20 => MsgKind::Chat,
            21 => MsgKind::PlayerInfoRequest,
            22 => MsgKind::PlayerInfoNack,
            23 => MsgKind::InventoryState,
            24 => MsgKind::TorchDiff,
            25 => MsgKind::WaterStateDiff,
            26 => MsgKind::SyncTick,
            27 => MsgKind::SyncAck,
            28 => MsgKind::WaterOriginsDiff,
            29 => MsgKind::SimTime,
            30 => MsgKind::BagState,
            31 => MsgKind::BentityDiff,
            32 => MsgKind::CropDiff,
            33 => MsgKind::AnimalState,
            34 => MsgKind::AnimalHit,
            _ => return None,
        })
    }
}

