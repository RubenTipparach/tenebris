/// `proto_write_hello`
pub fn write_hello(buf: &mut [u8], m: &MsgHello) -> usize {
    let total = MSG_HEADER_SIZE + MSG_HELLO_WIRE_SIZE;
    if buf.len() < total {
        return 0;
    }
    write_header(buf, MsgKind::Hello, MSG_HELLO_VERSION, MSG_HELLO_WIRE_SIZE as u32);
    let p = &mut buf[MSG_HEADER_SIZE..];
    put_u32_le(p, 0, m.client_version);
    p[4..4 + MSG_HELLO_TOKEN_LEN].copy_from_slice(&m.token);
    p[4 + MSG_HELLO_TOKEN_LEN..4 + MSG_HELLO_TOKEN_LEN + MSG_HELLO_NAME_LEN]
        .copy_from_slice(&m.name);
    let room_off = 4 + MSG_HELLO_TOKEN_LEN + MSG_HELLO_NAME_LEN;
    p[room_off..room_off + MSG_HELLO_ROOM_LEN].copy_from_slice(&m.room_code);
    put_u32_le(p, room_off + MSG_HELLO_ROOM_LEN, m.reserved);
    total
}

/// `proto_read_hello`
pub fn read_hello(payload: &[u8]) -> Option<MsgHello> {
    if payload.len() < MSG_HELLO_WIRE_SIZE {
        return None;
    }
    let mut out = MsgHello::default();
    out.client_version = get_u32_le(payload, 0);
    out.token.copy_from_slice(&payload[4..4 + MSG_HELLO_TOKEN_LEN]);
    out.name.copy_from_slice(
        &payload[4 + MSG_HELLO_TOKEN_LEN..4 + MSG_HELLO_TOKEN_LEN + MSG_HELLO_NAME_LEN],
    );
    let room_off = 4 + MSG_HELLO_TOKEN_LEN + MSG_HELLO_NAME_LEN;
    out.room_code
        .copy_from_slice(&payload[room_off..room_off + MSG_HELLO_ROOM_LEN]);
    out.reserved = get_u32_le(payload, room_off + MSG_HELLO_ROOM_LEN);
    Some(out)
}

