/// `proto_write_torch_diff`. Clamps `entry_count` to
/// TORCH_DIFF_MAX_ENTRIES, exactly like the C encoder.
pub fn write_torch_diff(buf: &mut [u8], m: &MsgTorchDiff) -> usize {
    let mut n = m.entry_count as usize;
    if n > TORCH_DIFF_MAX_ENTRIES {
        n = TORCH_DIFF_MAX_ENTRIES;
    }
    let payload_len = MSG_TORCH_DIFF_HEADER + n * MSG_TORCH_ENTRY_SIZE;
    let total = MSG_HEADER_SIZE + payload_len;
    if buf.len() < total {
        return 0;
    }
    write_header(buf, MsgKind::TorchDiff, MSG_TORCH_DIFF_VERSION, payload_len as u32);
    let p = &mut buf[MSG_HEADER_SIZE..];
    put_u32_le(p, 0, m.body_id);
    put_u16_le(p, 4, n as u16);
    put_u16_le(p, 6, 0);
    let mut off = MSG_TORCH_DIFF_HEADER;
    for e in &m.entries[..n] {
        /* Encode op + 3 reserved bytes as a u32 so the header stays
         * 4-byte aligned. Decoder reads the same way. Note: the
         * reserved bytes DO travel on the wire (the C encoder packs
         * them in, it does not zero them). */
        let op_field =
            (e.op as u32) | ((e.reserved8 as u32) << 8) | ((e.reserved16 as u32) << 16);
        put_u32_le(p, off, op_field);
        put_u32_le(p, off + 4, e.tile_idx);
        put_f32_le(p, off + 8, e.pos_x);
        put_f32_le(p, off + 12, e.pos_y);
        put_f32_le(p, off + 16, e.pos_z);
        put_f32_le(p, off + 20, e.up_x);
        put_f32_le(p, off + 24, e.up_y);
        put_f32_le(p, off + 28, e.up_z);
        off += MSG_TORCH_ENTRY_SIZE;
    }
    total
}

/// `proto_read_torch_diff`
pub fn read_torch_diff(payload: &[u8]) -> Option<MsgTorchDiff> {
    if payload.len() < MSG_TORCH_DIFF_HEADER {
        return None;
    }
    let mut out = MsgTorchDiff::default();
    out.body_id = get_u32_le(payload, 0);
    let n = get_u16_le(payload, 4) as usize;
    out.reserved = get_u16_le(payload, 6);
    if n > TORCH_DIFF_MAX_ENTRIES {
        return None;
    }
    if payload.len() < MSG_TORCH_DIFF_HEADER + n * MSG_TORCH_ENTRY_SIZE {
        return None;
    }
    out.entry_count = n as u16;
    let mut off = MSG_TORCH_DIFF_HEADER;
    for e in &mut out.entries[..n] {
        let op_field = get_u32_le(payload, off);
        e.op = (op_field & 0xFF) as u8;
        e.reserved8 = ((op_field >> 8) & 0xFF) as u8;
        e.reserved16 = ((op_field >> 16) & 0xFFFF) as u16;
        e.tile_idx = get_u32_le(payload, off + 4);
        e.pos_x = get_f32_le(payload, off + 8);
        e.pos_y = get_f32_le(payload, off + 12);
        e.pos_z = get_f32_le(payload, off + 16);
        e.up_x = get_f32_le(payload, off + 20);
        e.up_y = get_f32_le(payload, off + 24);
        e.up_z = get_f32_le(payload, off + 28);
        off += MSG_TORCH_ENTRY_SIZE;
    }
    Some(out)
}

