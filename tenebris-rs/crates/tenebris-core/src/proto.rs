    /// Encode `m`, parse the header, decode the payload, and return
    /// (header, decoded). Checks header kind/version/length invariants.
    fn round<T, W, R>(m: &T, kind: MsgKind, version: u16, w: W, r: R) -> T
    where
        W: Fn(&mut [u8], &T) -> usize,
        R: Fn(&[u8]) -> Option<T>,
    {
        let mut buf = vec![0u8; 8192];
        let n = w(&mut buf, m);
        assert!(n >= MSG_HEADER_SIZE);
        let hdr = read_header(&buf[..n]).expect("header");
        assert_eq!(hdr.kind, kind as u16);
        assert_eq!(hdr.version, version);
        assert_eq!(hdr.length as usize, n - MSG_HEADER_SIZE);
        r(&buf[MSG_HEADER_SIZE..n]).expect("decode")
    }

