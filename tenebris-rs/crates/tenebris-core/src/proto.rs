/* Header + body layout for MSG_WATER_ORIGINS_DIFF:
 *   uint32  body_id
 *   uint32  tile_idx
 *   uint16  entry_count        (number of (depth, origins) records)
 *   uint16  _pad
 *   entries[entry_count]:
 *     uint8  depth             (0..WORLD_MAX_DEPTH-1)
 *     uint8  origin_count      (1..3)
 *     uint8  _pad[2]
 *     uint32 origin_tile[3]    (only first origin_count are meaningful)
 *     uint8  origin_depth[3]
 *     uint8  _pad2
 *
 * Each entry is 20 bytes. A tile carrying its theoretical max of
 * WORLD_MAX_DEPTH=128 distinct flow cells = 2.5 KB which still
 * fits comfortably in a single WebSocket message. Practical waterfall
 * tiles carry <20 entries (~400 B). */
pub const MSG_WATER_ORIGINS_DIFF_HEADER_SIZE: usize = 12;
pub const MSG_WATER_ORIGINS_DIFF_ENTRY_SIZE: usize = 20;
pub const MSG_WATER_ORIGINS_DIFF_MAX_ENTRIES: usize = 128;
pub const MSG_WATER_ORIGINS_DIFF_MAX_SIZE: usize = MSG_WATER_ORIGINS_DIFF_HEADER_SIZE
    + MSG_WATER_ORIGINS_DIFF_ENTRY_SIZE * MSG_WATER_ORIGINS_DIFF_MAX_ENTRIES;

/// `msg_hdr_t`. `kind` stays a raw u16 like the C struct - decoding a
/// frame whose kind we don't know must still parse the header so the
/// peer can skip / close cleanly.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct MsgHdr {
    pub kind: u16,
    pub version: u16,
    /// payload bytes, not including header
    pub length: u32,
}

