#!/usr/bin/env python3
"""Generate the baked critter (NPC animal) model + animation clips.

Baked-asset path (CLAUDE.md static-asset guidelines): the .obj under
assets/models/ is the source of truth, with a JSON sidecar carrying the
rig's per-part pivots, and the walk / idle / death keyframe clips baked
to assets/animations/*.anim.json (frames + per-bone transforms).
Deterministic, stdlib only. Run from tenebris-rs/:

    python tools/gen-critter-model.py

Model conventions (must match client/baked_model.rs + animals.rs):
  - units are metres, origin at the feet, +Y up, the critter faces -Z
    (same frame the procedural box critter used).
  - each `o <name>` group is one rigid part (bone). No parent chains:
    head+snout+ears are merged into a single "head" part so they move
    together.
  - materials in the sibling .mtl give each face run its colour.
  - the sidecar critter.json maps part -> pivot (the joint the part
    rotates about; parts without an entry pivot at the origin).

Anim clip format (*.anim.json):
  { "name": "...", "duration_s": f, "loop": true|false,
    "bones": { "<part>": [ {"t": f, "rot": [xdeg,ydeg,zdeg],
                            "pos": [x,y,z]}, ... ] } }
  Tracks interpolate linearly between keys; "root" is a pseudo-bone
  applied to the whole model (used by the death roll).
"""

import json
import os

# ---------------------------------------------------------------------------
# OBJ emit helpers


class ObjWriter:
    def __init__(self):
        self.lines = []
        self.vbase = 1  # OBJ indices are 1-based

    def comment(self, s):
        self.lines.append("# " + s)

    def mtllib(self, name):
        self.lines.append("mtllib " + name)

    def group(self, name):
        self.lines.append("o " + name)

    def usemtl(self, name):
        self.lines.append("usemtl " + name)

    def cuboid(self, cx, cy, cz, hx, hy, hz):
        """Axis-aligned cuboid, 6 quads wound CCW from outside."""
        x0, x1 = cx - hx, cx + hx
        y0, y1 = cy - hy, cy + hy
        z0, z1 = cz - hz, cz + hz
        v = [
            (x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),  # -Z face ring
            (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1),  # +Z face ring
        ]
        for p in v:
            self.lines.append("v %.6f %.6f %.6f" % p)
        b = self.vbase
        quads = [
            (0, 3, 2, 1),  # -Z (front): CCW seen from -Z
            (4, 5, 6, 7),  # +Z (back)
            (0, 1, 5, 4),  # -Y (bottom)
            (3, 7, 6, 2),  # +Y (top)
            (0, 4, 7, 3),  # -X (left)
            (1, 2, 6, 5),  # +X (right)
        ]
        for q in quads:
            self.lines.append("f %d %d %d %d" % tuple(b + i for i in q))
        self.vbase += 8

    def text(self):
        return "\n".join(self.lines) + "\n"


# ---------------------------------------------------------------------------
# The critter: a deer-ish quadruped. Feet at y=0, faces -Z.

MATERIALS = {
    # name: (Kd r, g, b)
    "hide": (0.54, 0.40, 0.26),        # warm brown torso
    "hide_light": (0.62, 0.48, 0.32),  # head / chest highlight
    "hide_dark": (0.42, 0.31, 0.21),   # legs / ears / tail
    "snout": (0.33, 0.24, 0.17),       # dark muzzle
    "belly": (0.68, 0.58, 0.44),       # pale underside strip
}

# Per-part pivots (the joint each part rotates about).
PIVOTS = {
    "body": [0.0, 0.47, 0.05],
    "head": [0.0, 0.55, -0.28],   # neck joint
    "tail": [0.0, 0.52, 0.28],    # tail base
    "leg_fl": [-0.11, 0.36, -0.20],
    "leg_fr": [0.11, 0.36, -0.20],
    "leg_bl": [-0.11, 0.36, 0.20],
    "leg_br": [0.11, 0.36, 0.20],
}


def build_critter():
    w = ObjWriter()
    w.comment("tenebris baked critter - generated by tools/gen-critter-model.py")
    w.comment("units m, feet at y=0, +Y up, faces -Z")
    w.mtllib("critter.mtl")

    # Torso: main barrel + deeper chest + pale belly strip.
    w.group("body")
    w.usemtl("hide")
    w.cuboid(0.0, 0.47, 0.06, 0.17, 0.13, 0.25)
    w.usemtl("hide_light")
    w.cuboid(0.0, 0.46, -0.19, 0.155, 0.145, 0.10)
    w.usemtl("belly")
    w.cuboid(0.0, 0.355, 0.02, 0.12, 0.02, 0.20)

    # Head: skull + snout + ears, one rigid part pivoting at the neck.
    w.group("head")
    w.usemtl("hide_light")
    w.cuboid(0.0, 0.62, -0.38, 0.10, 0.10, 0.09)
    w.usemtl("snout")
    w.cuboid(0.0, 0.575, -0.515, 0.055, 0.05, 0.05)
    w.usemtl("hide_dark")
    w.cuboid(-0.075, 0.765, -0.36, 0.025, 0.05, 0.015)
    w.cuboid(0.075, 0.765, -0.36, 0.025, 0.05, 0.015)

    w.group("tail")
    w.usemtl("hide_dark")
    w.cuboid(0.0, 0.52, 0.345, 0.03, 0.03, 0.065)

    # Legs, pivoting at the hips/shoulders (y = 0.36).
    for name, sx, sz in (
        ("leg_fl", -1, -1),
        ("leg_fr", 1, -1),
        ("leg_bl", -1, 1),
        ("leg_br", 1, 1),
    ):
        w.group(name)
        w.usemtl("hide_dark")
        w.cuboid(0.11 * sx, 0.18, 0.20 * sz, 0.045, 0.18, 0.045)

    return w.text()


def build_mtl():
    lines = ["# critter materials - generated by tools/gen-critter-model.py"]
    for name, (r, g, b) in MATERIALS.items():
        lines.append("newmtl " + name)
        lines.append("Kd %.4f %.4f %.4f" % (r, g, b))
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Animation clips. rot in degrees (XYZ euler about the part pivot),
# pos in metres. Linear interpolation between keys.


def key(t, rot=None, pos=None):
    k = {"t": round(t, 4)}
    if rot is not None:
        k["rot"] = rot
    if pos is not None:
        k["pos"] = pos
    return k


def walk_clip():
    """Diagonal gait: FL+BR swing together, FR+BL opposite; body bobs,
    head counter-bobs, tail wags."""
    d = 0.8
    swing = 26.0
    fwd = [key(0.0, rot=[swing, 0, 0]), key(d * 0.5, rot=[-swing, 0, 0]), key(d, rot=[swing, 0, 0])]
    back = [key(0.0, rot=[-swing, 0, 0]), key(d * 0.5, rot=[swing, 0, 0]), key(d, rot=[-swing, 0, 0])]
    bob = [
        key(0.0, pos=[0, 0.0, 0]),
        key(d * 0.25, pos=[0, 0.016, 0]),
        key(d * 0.5, pos=[0, 0.0, 0]),
        key(d * 0.75, pos=[0, 0.016, 0]),
        key(d, pos=[0, 0.0, 0]),
    ]
    head = [
        key(0.0, rot=[3, 0, 0]),
        key(d * 0.25, rot=[-2, 0, 0]),
        key(d * 0.5, rot=[3, 0, 0]),
        key(d * 0.75, rot=[-2, 0, 0]),
        key(d, rot=[3, 0, 0]),
    ]
    tail = [key(0.0, rot=[0, 14, 0]), key(d * 0.5, rot=[0, -14, 0]), key(d, rot=[0, 14, 0])]
    return {
        "name": "walk",
        "duration_s": d,
        "loop": True,
        "bones": {
            "leg_fl": fwd,
            "leg_br": fwd,
            "leg_fr": back,
            "leg_bl": back,
            "body": bob,
            "head": head,
            "tail": tail,
        },
    }


def idle_clip():
    """Grazing nod + breathing + ear-twitch-adjacent tail sway."""
    d = 2.4
    head = [
        key(0.0, rot=[0, 0, 0]),
        key(0.7, rot=[14, 0, 0]),   # dip to graze
        key(1.3, rot=[14, 6, 0]),   # look aside
        key(1.8, rot=[2, 0, 0]),
        key(d, rot=[0, 0, 0]),
    ]
    breathe = [
        key(0.0, pos=[0, 0.0, 0]),
        key(d * 0.5, pos=[0, 0.007, 0]),
        key(d, pos=[0, 0.0, 0]),
    ]
    tail = [
        key(0.0, rot=[0, 6, 0]),
        key(0.9, rot=[0, -8, 0]),
        key(1.1, rot=[0, 8, 0]),  # quick flick
        key(d, rot=[0, 6, 0]),
    ]
    return {
        "name": "idle",
        "duration_s": d,
        "loop": True,
        "bones": {"head": head, "body": breathe, "tail": tail},
    }


def death_clip():
    """Keel over sideways: whole-model roll (root pseudo-bone) with a
    sink onto the flank, legs kicking out then going stiff."""
    d = 0.7
    root = [
        key(0.0, rot=[0, 0, 0], pos=[0, 0, 0]),
        key(0.3, rot=[0, 0, 62], pos=[0, -0.05, 0]),
        key(0.5, rot=[0, 0, 96], pos=[0, -0.24, 0]),   # slight overshoot
        key(d, rot=[0, 0, 90], pos=[0, -0.22, 0]),
    ]
    kick = [
        key(0.0, rot=[0, 0, 0]),
        key(0.25, rot=[34, 0, 0]),
        key(0.5, rot=[-8, 0, 0]),
        key(d, rot=[6, 0, 0]),
    ]
    kick2 = [
        key(0.0, rot=[0, 0, 0]),
        key(0.25, rot=[-30, 0, 0]),
        key(0.5, rot=[12, 0, 0]),
        key(d, rot=[-4, 0, 0]),
    ]
    head = [
        key(0.0, rot=[0, 0, 0]),
        key(0.35, rot=[-26, 0, 0]),  # head throws back
        key(d, rot=[-14, 0, 0]),
    ]
    return {
        "name": "death",
        "duration_s": d,
        "loop": False,
        "bones": {
            "root": root,
            "leg_fl": kick,
            "leg_br": kick,
            "leg_fr": kick2,
            "leg_bl": kick2,
            "head": head,
        },
    }


# ---------------------------------------------------------------------------


def main():
    models = os.path.join("assets", "models")
    anims = os.path.join("assets", "animations")
    os.makedirs(models, exist_ok=True)
    os.makedirs(anims, exist_ok=True)

    with open(os.path.join(models, "critter.obj"), "w") as f:
        f.write(build_critter())
    print("wrote", os.path.join(models, "critter.obj"))

    with open(os.path.join(models, "critter.mtl"), "w") as f:
        f.write(build_mtl())
    print("wrote", os.path.join(models, "critter.mtl"))

    with open(os.path.join(models, "critter.json"), "w") as f:
        json.dump({"pivots": PIVOTS}, f, indent=2, sort_keys=True)
        f.write("\n")
    print("wrote", os.path.join(models, "critter.json"))

    for clip in (walk_clip(), idle_clip(), death_clip()):
        path = os.path.join(anims, "critter_%s.anim.json" % clip["name"])
        with open(path, "w") as f:
            json.dump(clip, f, indent=1, sort_keys=True)
            f.write("\n")
        print("wrote", path)


if __name__ == "__main__":
    main()
