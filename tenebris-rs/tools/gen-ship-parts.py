class Obj:
    """Tiny OBJ emitter matching baked_model.rs's parser subset."""

    def __init__(self, name):
        self.name = name
        self.lines = ["# generated by tools/gen-ship-parts.py - do not hand-edit",
                      "mtllib ship_%s.mtl" % name]
        self.n = 1
        self.mats = set()

    def group(self, g):
        self.lines.append("o " + g)

    def mat(self, m):
        self.mats.add(m)
        self.lines.append("usemtl " + m)

    def _emit(self, verts, faces):
        for v in verts:
            self.lines.append("v %.5f %.5f %.5f" % v)
        for f in faces:
            self.lines.append("f " + " ".join(str(self.n + i) for i in f))
        self.n += len(verts)

    def box(self, c, h, rot=None):
        """Axis-aligned box at centre c with half-extents h, optional
        (axis, degrees) rotation about its own centre baked in."""
        verts = []
        for dz in (-h[2], h[2]):
            for dy in (-h[1], h[1]):
                for dx in (-h[0], h[0]):
                    p = [dx, dy, dz]
                    if rot:
                        p = _rot(p, rot[0], rot[1])
                    verts.append((c[0] + p[0], c[1] + p[1], c[2] + p[2]))
        # 0=(-,-,-) 1=(+,-,-) 2=(-,+,-) 3=(+,+,-) 4..7 = same at +z
        self._emit(verts, [(0, 1, 3, 2), (5, 4, 6, 7), (4, 5, 1, 0),
                           (2, 3, 7, 6), (4, 0, 2, 6), (1, 5, 7, 3)])

    def tube(self, y0, y1, r0, r1, sides=6, cx=0.0, cz=0.0, caps=True, phase=0.0):
        """Prism / frustum along +Y. sides=6 gives the house hex look."""
        ring0, ring1 = [], []
        for i in range(sides):
            a = phase + 2.0 * math.pi * i / sides
            ring0.append((cx + r0 * math.cos(a), y0, cz + r0 * math.sin(a)))
            ring1.append((cx + r1 * math.cos(a), y1, cz + r1 * math.sin(a)))
        verts = ring0 + ring1
        faces = []
        for i in range(sides):
            j = (i + 1) % sides
            faces.append((i, j, sides + j, sides + i))
        if caps:
            faces.append(tuple(range(sides - 1, -1, -1)))
            faces.append(tuple(range(sides, 2 * sides)))
        self._emit(verts, faces)

    def tube_axis(self, p0, p1, r0, r1, sides=6, caps=True):
        """Prism between two arbitrary points (struts, coils, hooks)."""
        d = [p1[i] - p0[i] for i in range(3)]
        L = math.sqrt(sum(x * x for x in d)) or 1e-6
        ax = [x / L for x in d]
        tmp = [0.0, 0.0, 1.0] if abs(ax[1]) > 0.9 else [0.0, 1.0, 0.0]
        u = _norm(_cross(ax, tmp))
        w = _cross(ax, u)
        verts = []
        for (base, r) in ((p0, r0), (p1, r1)):
            for i in range(sides):
                a = 2.0 * math.pi * i / sides
                verts.append(tuple(base[k] + r * (math.cos(a) * u[k] + math.sin(a) * w[k])
                                   for k in range(3)))
        faces = []
        for i in range(sides):
            j = (i + 1) % sides
            faces.append((i, j, sides + j, sides + i))
        if caps:
            faces.append(tuple(range(sides - 1, -1, -1)))
            faces.append(tuple(range(sides, 2 * sides)))
        self._emit(verts, faces)

    def write(self, path):
        open(path, "w").write("\n".join(self.lines) + "\n")
        mtl = ["# generated by tools/gen-ship-parts.py"]
        for m in sorted(self.mats):
            r, g, b = MTL[m]
            mtl += ["newmtl " + m, "Kd %.4f %.4f %.4f" % (r, g, b), ""]
        open(path[:-4] + ".mtl", "w").write("\n".join(mtl) + "\n")


def _cross(a, b):
    return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]


def _norm(v):
    m = math.sqrt(sum(c * c for c in v)) or 1.0
    return [c / m for c in v]


def _rot(p, axis, deg):
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    x, y, z = p
    if axis == "x":
        return [x, y * c - z * s, y * s + z * c]
    if axis == "y":
        return [x * c + z * s, y, -x * s + z * c]
    return [x * c - y * s, x * s + y * c, z]


def node(pos, dir_, kind):
    return {"pos": [round(v, 4) for v in pos], "dir": [round(v, 4) for v in dir_], "kind": kind}


