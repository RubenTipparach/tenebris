def tris_of(obj):
    """Re-read the emitted lines into triangles + colours."""
    verts, tris, cur = [], [], (0.75, 0.75, 0.78)
    for line in obj.lines:
        p = line.split()
        if not p:
            continue
        if p[0] == "v":
            verts.append((float(p[1]), float(p[2]), float(p[3])))
        elif p[0] == "usemtl":
            cur = MTL[p[1]]
        elif p[0] == "f":
            idx = [int(t.split("/")[0]) - 1 for t in p[1:]]
            for k in range(1, len(idx) - 1):
                tris.append((verts[idx[0]], verts[idx[k]], verts[idx[k + 1]], cur))
    return tris


def render(tris, w, h, yaw=0.62, pitch=0.30, ss=3, bg=None):
    """Supersampled render. bg=None -> transparent (icons)."""
    W, H = w * ss, h * ss
    pts = [v for t in tris for v in t[:3]]
    lo = [min(p[i] for p in pts) for i in range(3)]
    hi = [max(p[i] for p in pts) for i in range(3)]
    ctr = [(lo[i] + hi[i]) * 0.5 for i in range(3)]
    rad = max(max(hi[i] - lo[i] for i in range(3)) * 0.5, 1e-4)
    dist = rad * 3.0
    cy, sy = math.cos(yaw), math.sin(yaw)
    cp, sp = math.cos(pitch), math.sin(pitch)
    eye = (ctr[0] + dist * cp * sy, ctr[1] + dist * sp, ctr[2] + dist * cp * cy)
    fwd = _norm([ctr[i] - eye[i] for i in range(3)])
    right = _norm([fwd[2], 0.0, -fwd[0]])
    # cross(fwd, right), NOT cross(right, fwd) - the latter yields -Y and
    # renders every model upside down (the cruise thruster's bell ends up
    # at the top, the landing strut stands on its foot pad).
    up = _norm(_cross(fwd, right))
    fl = 1.55 * min(W, H) * 0.5
    light = _norm([-0.45, 0.80, 0.40])
    zb = [[1e30] * W for _ in range(H)]
    px = [[(0, 0, 0, 0)] * W for _ in range(H)]

    def proj(p):
        d = [p[i] - eye[i] for i in range(3)]
        z = sum(d[i] * fwd[i] for i in range(3))
        if z <= 1e-5:
            return None
        return (W * 0.5 + fl * sum(d[i] * right[i] for i in range(3)) / z,
                H * 0.5 - fl * sum(d[i] * up[i] for i in range(3)) / z, z)

    for (a, b, c, col) in tris:
        e1 = [b[i] - a[i] for i in range(3)]
        e2 = [c[i] - a[i] for i in range(3)]
        n = _norm(_cross(e1, e2))
        shade = 0.55 + 0.45 * (0.5 + 0.5 * max(-1.0, min(1.0, n[1])))  # baked_model.rs
        key = max(0.0, sum(n[i] * light[i] for i in range(3)))
        lit = min(1.0, shade * (0.70 + 0.58 * key))
        rgb = tuple(int(max(0, min(255, 255 * col[i] * lit))) for i in range(3)) + (255,)
        P = [proj(v) for v in (a, b, c)]
        if any(p is None for p in P):
            continue
        x0 = max(0, int(min(p[0] for p in P)))
        x1 = min(W - 1, int(max(p[0] for p in P)) + 1)
        y0 = max(0, int(min(p[1] for p in P)))
        y1 = min(H - 1, int(max(p[1] for p in P)) + 1)
        det = ((P[1][0] - P[0][0]) * (P[2][1] - P[0][1])
               - (P[2][0] - P[0][0]) * (P[1][1] - P[0][1]))
        if abs(det) < 1e-9:
            continue
        for yy in range(y0, y1 + 1):
            for xx in range(x0, x1 + 1):
                sx, sy_ = xx + 0.5, yy + 0.5
                w0 = ((P[1][0] - sx) * (P[2][1] - sy_) - (P[2][0] - sx) * (P[1][1] - sy_)) / det
                w1 = ((P[2][0] - sx) * (P[0][1] - sy_) - (P[0][0] - sx) * (P[2][1] - sy_)) / det
                if w0 < 0 or w1 < 0 or 1.0 - w0 - w1 < 0:
                    continue
                z = w0 * P[0][2] + w1 * P[1][2] + (1 - w0 - w1) * P[2][2]
                if z < zb[yy][xx]:
                    zb[yy][xx] = z
                    px[yy][xx] = rgb
    # box-filter down
    out = []
    for y in range(h):
        row = []
        for x in range(w):
            acc = [0, 0, 0, 0]
            for dy in range(ss):
                for dx in range(ss):
                    p = px[y * ss + dy][x * ss + dx]
                    if p[3]:
                        acc[0] += p[0]; acc[1] += p[1]; acc[2] += p[2]
                    acc[3] += p[3]
            cov = acc[3] // 255
            if cov == 0:
                row.append(bg + (255,) if bg else (0, 0, 0, 0))
            else:
                a = acc[3] // (ss * ss)
                col = (acc[0] // cov, acc[1] // cov, acc[2] // cov)
                if bg:
                    f = a / 255.0
                    row.append(tuple(int(col[i] * f + bg[i] * (1 - f)) for i in range(3)) + (255,))
                else:
                    row.append(col + (a,))
        out.append(row)
    return out


def write_png(path, rows):
    h, w = len(rows), len(rows[0])
    raw = bytearray()
    for r in rows:
        raw.append(0)
        for p in r:
            raw.extend(p)

    def chunk(tag, d):
        return struct.pack(">I", len(d)) + tag + d + struct.pack(">I", zlib.crc32(tag + d) & 0xFFFFFFFF)

    open(path, "wb").write(b"\x89PNG\r\n\x1a\n"
                           + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
                           + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
                           + chunk(b"IEND", b""))


