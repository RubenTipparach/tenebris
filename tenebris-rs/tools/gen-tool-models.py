#!/usr/bin/env python3
"""Generate the baked 3D tool models (wood pickaxe / axe / shovel).

Baked-asset path (CLAUDE.md static-asset guidelines): .obj source of
truth under assets/models/, JSON pivot sidecar alongside. Rendered by
the first-person viewmodel (client/viewmodel.rs). Deterministic, stdlib
only. Run from tenebris-rs/:

    python tools/gen-tool-models.py

Conventions: units m, handle runs along +Y with the grip at y=0, the
business end at the top (y ~ 0.7); the head faces -Z where it matters
(axe blade / shovel scoop). Rotated cuboids are baked into the verts.
"""

import json
import math
import os

MATERIALS = {
    "handle": (0.52, 0.36, 0.20),   # lighter shaft wood
    "head": (0.38, 0.26, 0.14),     # darker head wood
    "lash": (0.24, 0.17, 0.10),     # binding wrap
}

HANDLE_LEN = 0.68
HANDLE_HALF = 0.026


class ObjWriter:
    def __init__(self):
        self.lines = []
        self.vbase = 1

    def comment(self, s):
        self.lines.append("# " + s)

    def mtllib(self, name):
        self.lines.append("mtllib " + name)

    def group(self, name):
        self.lines.append("o " + name)

    def usemtl(self, name):
        self.lines.append("usemtl " + name)

    def cuboid(self, cx, cy, cz, hx, hy, hz, rotz=0.0, rotx=0.0):
        """Cuboid, optionally rotated about its own centre (Z then X,
        degrees) - the rotation is baked into the emitted vertices."""
        corners = []
        for dz in (-hz, hz):
            for dy in (-hy, hy):
                for dx in (-hx, hx):
                    corners.append((dx, dy, dz))
        rz = math.radians(rotz)
        rx = math.radians(rotx)
        cz_, sz_ = math.cos(rz), math.sin(rz)
        cx_, sx_ = math.cos(rx), math.sin(rx)
        out = []
        for (dx, dy, dz) in corners:
            # rotate about Z
            dx, dy = dx * cz_ - dy * sz_, dx * sz_ + dy * cz_
            # rotate about X
            dy, dz = dy * cx_ - dz * sx_, dy * sx_ + dz * cx_
            out.append((cx + dx, cy + dy, cz + dz))
        for p in out:
            self.lines.append("v %.6f %.6f %.6f" % p)
        b = self.vbase
        # corner order: 0=(--,-z) 1=(+-) 2=(-+) 3=(++) then +z 4..7
        quads = [
            (0, 2, 3, 1),  # -Z
            (4, 5, 7, 6),  # +Z
            (0, 1, 5, 4),  # -Y
            (2, 6, 7, 3),  # +Y
            (0, 4, 6, 2),  # -X
            (1, 3, 7, 5),  # +X
        ]
        for q in quads:
            self.lines.append("f %d %d %d %d" % tuple(b + i for i in q))
        self.vbase += 8

    def text(self):
        return "\n".join(self.lines) + "\n"


def handle(w):
    w.group("handle")
    w.usemtl("handle")
    w.cuboid(0.0, HANDLE_LEN * 0.5, 0.0, HANDLE_HALF, HANDLE_LEN * 0.5, HANDLE_HALF)
    # binding wrap just under the head
    w.usemtl("lash")
    w.cuboid(0.0, HANDLE_LEN - 0.05, 0.0, HANDLE_HALF + 0.008, 0.018, HANDLE_HALF + 0.008)


def pickaxe():
    w = ObjWriter()
    w.comment("wood pickaxe - generated by tools/gen-tool-models.py")
    w.mtllib("wood_pickaxe.mtl")
    handle(w)
    w.group("head")
    w.usemtl("head")
    # centre bar across the top, plus two down-curved tips (baked rot).
    w.cuboid(0.0, HANDLE_LEN, 0.0, 0.030, 0.034, 0.10)
    w.cuboid(0.0, HANDLE_LEN - 0.035, -0.155, 0.026, 0.030, 0.085, rotx=-32.0)
    w.cuboid(0.0, HANDLE_LEN - 0.035, 0.155, 0.026, 0.030, 0.085, rotx=32.0)
    return w.text()


def axe():
    w = ObjWriter()
    w.comment("wood axe - generated by tools/gen-tool-models.py")
    w.mtllib("wood_axe.mtl")
    handle(w)
    w.group("head")
    w.usemtl("head")
    # blade block on the -Z side + thinner bevelled edge
    w.cuboid(0.0, HANDLE_LEN - 0.02, -0.065, 0.030, 0.075, 0.045)
    w.cuboid(0.0, HANDLE_LEN - 0.02, -0.125, 0.016, 0.095, 0.022, rotz=0.0)
    return w.text()


def shovel():
    w = ObjWriter()
    w.comment("wood shovel - generated by tools/gen-tool-models.py")
    w.mtllib("wood_shovel.mtl")
    handle(w)
    w.group("head")
    w.usemtl("head")
    # scoop: broad plate tilted slightly back, plus side lips
    w.cuboid(0.0, HANDLE_LEN + 0.06, 0.008, 0.058, 0.085, 0.014, rotx=8.0)
    w.usemtl("lash")
    w.cuboid(-0.052, HANDLE_LEN + 0.05, 0.014, 0.008, 0.062, 0.018, rotx=8.0)
    w.cuboid(0.052, HANDLE_LEN + 0.05, 0.014, 0.008, 0.062, 0.018, rotx=8.0)
    return w.text()


def build_mtl():
    lines = ["# wood tool materials - generated by tools/gen-tool-models.py"]
    for name, (r, g, b) in MATERIALS.items():
        lines.append("newmtl " + name)
        lines.append("Kd %.4f %.4f %.4f" % (r, g, b))
    return "\n".join(lines) + "\n"


def main():
    out = os.path.join("assets", "models")
    os.makedirs(out, exist_ok=True)
    tools = {"wood_pickaxe": pickaxe(), "wood_axe": axe(), "wood_shovel": shovel()}
    mtl = build_mtl()
    for name, obj in tools.items():
        with open(os.path.join(out, name + ".obj"), "w") as f:
            f.write(obj)
        with open(os.path.join(out, name + ".mtl"), "w") as f:
            f.write(mtl)
        # No articulated parts on a tool: empty pivot sidecar keeps the
        # loader path uniform with critter.json.
        with open(os.path.join(out, name + ".json"), "w") as f:
            json.dump({"pivots": {}}, f)
            f.write("\n")
        print("wrote", os.path.join(out, name + ".obj"))


if __name__ == "__main__":
    main()
